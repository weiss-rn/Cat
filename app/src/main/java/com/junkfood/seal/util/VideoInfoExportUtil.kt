package com.junkfood.seal.util

import androidx.annotation.CheckResult
import com.junkfood.seal.database.objects.SavedVideoInfo
import java.io.File
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json

/**
 * Shared "video information" text export used by both the download engine
 * ([DownloadUtil.writeDocsTextFile]) and the "Video Info Download" tool's saved cards
 * ([exportAsTxt]). All variants render into the same banner layout, so the format lives here
 * exactly once. Files are written to the app's docs directory (see [FileUtil.getDocsDirectory]).
 */
object VideoInfoExportUtil {

    private val prettyJson = Json {
        prettyPrint = true
        encodeDefaults = true
    }

    internal const val INFO_BANNER_SEPARATOR = "═══════════════════════════════════════"

    /** Appends the standard footer banner shared by every info-file variant. */
    private fun StringBuilder.appendFooter() {
        appendLine(INFO_BANNER_SEPARATOR)
        appendLine("  Generated by Cat")
        appendLine(INFO_BANNER_SEPARATOR)
    }

    /** Appends an optional labelled section; no-ops when [value] is null/blank. */
    private fun StringBuilder.appendSection(label: String, value: String?) {
        if (!value.isNullOrBlank()) {
            appendLine(label)
            appendLine(value)
            appendLine()
        }
    }

    /**
     * Renders a freshly fetched [VideoInfo] as the standard info TXT content.
     * Duration is formatted as "Xm Ys"; absent fields are skipped.
     */
    internal fun renderVideoInfoTxt(videoInfo: VideoInfo): String = buildString {
        appendLine(INFO_BANNER_SEPARATOR)
        appendLine("  VIDEO INFORMATION")
        appendLine(INFO_BANNER_SEPARATOR)
        appendLine()
        appendSection("Title:", videoInfo.title)
        appendSection("Uploader:", videoInfo.uploader)
        appendSection("Upload Date:", videoInfo.uploadDate)
        videoInfo.duration?.let { sec ->
            appendSection(
                "Duration:",
                "${(sec / 60).toInt()}m ${(sec % 60).toInt()}s",
            )
        }
        appendSection("URL:", videoInfo.webpageUrl)
        videoInfo.tags?.let { tags ->
            if (tags.isNotEmpty()) {
                appendLine("Tags:")
                tags.forEach { tag -> appendLine("  • $tag") }
                appendLine()
            }
        }
        appendSection("Description:", videoInfo.description)
        appendFooter()
    }

    /**
     * Renders a [SavedVideoInfo] database card as the standard info TXT content.
     * Blank fields are skipped; counts are only shown when present (>= 0).
     */
    internal fun renderSavedVideoInfoTxt(info: SavedVideoInfo): String = buildString {
        appendLine(INFO_BANNER_SEPARATOR)
        appendLine("  VIDEO INFORMATION")
        appendLine(INFO_BANNER_SEPARATOR)
        appendLine()
        appendSection("Title:", info.title)
        appendSection("Uploader:", info.uploader)
        appendSection("Upload Date:", info.uploadDate)
        appendSection("Duration:", info.durationString)
        if (info.viewCount >= 0) appendSection("Views:", info.viewCount.toString())
        if (info.likeCount >= 0) appendSection("Likes:", info.likeCount.toString())
        appendSection("URL:", info.videoUrl)
        if (info.tags.isNotEmpty()) {
            appendLine("Tags:")
            info.tags.forEach { tag -> appendLine("  • $tag") }
            appendLine()
        }
        appendSection("Description:", info.description)
        appendFooter()
    }

    private fun safeFileName(title: String): String =
        title.ifBlank { "video_info" }.replace(Regex("""[<>:"/\\|?*]"""), "_").take(100)

    @CheckResult
    fun exportAsTxt(info: SavedVideoInfo): Result<String> = runCatching {
        val docsDir = FileUtil.getDocsDirectory()
        val file = File(docsDir, "${safeFileName(info.title)} - Info.txt")
        FileUtil.writeContentToFile(renderSavedVideoInfoTxt(info), file)
        file.absolutePath
    }

    @CheckResult
    fun exportAsJson(info: SavedVideoInfo): Result<String> = runCatching {
        val docsDir = FileUtil.getDocsDirectory()
        val file = File(docsDir, "${safeFileName(info.title)} - Info.json")
        val exportModel = VideoInfoJsonExport(
            title = info.title,
            description = info.description,
            tags = info.tags,
            videoUrl = info.videoUrl,
            thumbnailUrl = info.thumbnailUrl,
            uploader = info.uploader,
            uploadDate = info.uploadDate,
            duration = info.durationString,
            viewCount = info.viewCount.takeIf { it >= 0 },
            likeCount = info.likeCount.takeIf { it >= 0 },
            extractor = info.extractor,
        )
        val content = prettyJson.encodeToString(exportModel)
        FileUtil.writeContentToFile(content, file)
        file.absolutePath
    }

    @kotlinx.serialization.Serializable
    private data class VideoInfoJsonExport(
        val title: String,
        val description: String,
        val tags: List<String>,
        val videoUrl: String,
        val thumbnailUrl: String,
        val uploader: String,
        val uploadDate: String,
        val duration: String,
        val viewCount: Long?,
        val likeCount: Long?,
        val extractor: String,
    )
}
